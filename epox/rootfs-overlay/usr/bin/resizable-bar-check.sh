#!/usr/bin/env bash

# resizable-bar-check.sh
#
# Linux Resizable BAR checker for GNOME.
#
# Runs from GNOME autostart.
#
# Checks:
#   - Once every 7 days
#   - Immediately when the GPU configuration changes
#
# If ReBAR is supported but not fully enabled, a native
# GTK4/GJS GNOME window is displayed.
#
# This script is READ-ONLY. It never modifies BIOS settings,
# PCI configuration, kernel parameters, or driver settings.
#
# It is also non-interactive: it never prompts for a password.
# If privileged PCI information is genuinely required it uses
# `sudo -n`, which fails immediately instead of prompting.

set -u
set -o pipefail

STATE_DIR="${XDG_CACHE_HOME:-"$HOME/.cache"}/resizable-bar-check"
STATE_FILE="$STATE_DIR/state"

CHECK_INTERVAL=$((7 * 24 * 60 * 60))

DIALOG="/usr/local/bin/resizable-bar-warning.js"

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
RESET='\033[0m'

info() {
    printf "${BLUE}[INFO]${RESET} %s\n" "$*"
}

good() {
    printf "${GREEN}[ OK ]${RESET} %s\n" "$*"
}

warn() {
    printf "${YELLOW}[WARN]${RESET} %s\n" "$*"
}

bad() {
    printf "${RED}[FAIL]${RESET} %s\n" "$*"
}

# ------------------------------------------------------------
# Convert a BAR size such as 256MB, 8GB or 16GiB to MiB.
# Supports MB/GB (and MiB/GiB). Prints nothing on failure.
# ------------------------------------------------------------

size_to_mib() {
    local size="$1"
    local number unit

    number=$(sed -E 's/^[[:space:]]*([0-9]+).*/\1/' <<< "$size")
    unit=$(sed -E 's/^[[:space:]]*[0-9]+[[:space:]]*([A-Za-z].*)$/\1/' <<< "$size")

    if [[ -z "$number" ]]; then
        echo ""
        return
    fi

    case "$unit" in
        GB|GiB)
            echo $((number * 1024))
            ;;
        MB|MiB)
            echo "$number"
            ;;
        TB|TiB)
            echo $((number * 1024 * 1024))
            ;;
        *)
            echo ""
            ;;
    esac
}

# ------------------------------------------------------------
# Requirements
# ------------------------------------------------------------

if ! command -v lspci >/dev/null 2>&1; then
    echo "ERROR: pciutils is required."
    exit 1
fi

if ! command -v gjs >/dev/null 2>&1; then
    echo "ERROR: gjs is required for the GNOME GUI."
    exit 1
fi

if [[ ! -x "$DIALOG" ]]; then
    echo "ERROR: GUI helper not found:"
    echo "$DIALOG"
    exit 1
fi

mkdir -p "$STATE_DIR"

# ------------------------------------------------------------
# Find GPUs
# ------------------------------------------------------------

mapfile -t GPU_LINES < <(
    lspci -D -nn 2>/dev/null |
        grep -Ei \
        'VGA compatible controller|3D controller|Display controller' ||
        true
)

if (( ${#GPU_LINES[@]} == 0 )); then
    bad "No GPUs detected."
    exit 1
fi

GPU_LIST=$(printf '%s\n' "${GPU_LINES[@]}")

# ------------------------------------------------------------
# Generate GPU configuration fingerprint
# ------------------------------------------------------------

if command -v sha256sum >/dev/null 2>&1; then
    GPU_HASH=$(
        printf '%s\n' "$GPU_LIST" |
            sha256sum |
            awk '{print $1}'
    )
else
    GPU_HASH=$(
        printf '%s\n' "$GPU_LIST" |
            cksum |
            awk '{print $1}'
    )
fi

# ------------------------------------------------------------
# Load state
# ------------------------------------------------------------

LAST_CHECK=0
OLD_GPU_HASH=""

if [[ -f "$STATE_FILE" ]]; then
    # The state file is generated by us and contains only
    # LAST_CHECK and OLD_GPU_HASH.
    # shellcheck disable=SC1090
    source "$STATE_FILE" 2>/dev/null || true
fi

LAST_CHECK="${LAST_CHECK:-0}"
OLD_GPU_HASH="${OLD_GPU_HASH:-}"

NOW=$(date +%s)

GPU_CHANGED=0
WEEKLY_CHECK=0

if [[ "$GPU_HASH" != "$OLD_GPU_HASH" ]]; then
    GPU_CHANGED=1
fi

if (( NOW - LAST_CHECK >= CHECK_INTERVAL )); then
    WEEKLY_CHECK=1
fi

# Nothing needs checking: exit silently.
if (( GPU_CHANGED == 0 && WEEKLY_CHECK == 0 )); then
    exit 0
fi

# ------------------------------------------------------------
# Save state before checking
# ------------------------------------------------------------

cat > "$STATE_FILE" <<EOF
LAST_CHECK=$NOW
OLD_GPU_HASH='$GPU_HASH'
EOF

# ------------------------------------------------------------
# Helper for native GNOME popup
# ------------------------------------------------------------

show_warning() {
    local gpu="$1"
    local reason="$2"

    # The autostart process already belongs to the user's
    # graphical GNOME session, so GJS can connect directly
    # to the session display.

    gjs "$DIALOG" "$gpu" "$reason" >/dev/null 2>&1 &
}

# ------------------------------------------------------------
# Header
# ------------------------------------------------------------

echo
echo "=============================================="
echo "       Linux Resizable BAR Checker"
echo "=============================================="
echo

if (( GPU_CHANGED )); then
    info "GPU configuration changed."
    info "Performing an immediate Resizable BAR check."
elif (( WEEKLY_CHECK )); then
    info "Performing scheduled weekly Resizable BAR check."
fi

# ------------------------------------------------------------
# UEFI detection
# ------------------------------------------------------------

if [[ -d /sys/firmware/efi ]]; then
    UEFI=1
    good "System booted in UEFI mode."
else
    UEFI=0
    warn "System appears to be booted in Legacy/BIOS mode."
fi

echo

# ------------------------------------------------------------
# GPU list
# ------------------------------------------------------------

echo "Detected GPU(s):"

for GPU_LINE in "${GPU_LINES[@]}"; do
    echo "  $GPU_LINE"
done

echo

# ------------------------------------------------------------
# Process GPUs
# ------------------------------------------------------------

REBAR_DISABLED=0
REBAR_UNKNOWN=0

for GPU_LINE in "${GPU_LINES[@]}"; do

    PCI_ADDR=$(awk '{print $1}' <<< "$GPU_LINE")

    echo "----------------------------------------------"
    echo "GPU: $PCI_ADDR"
    echo "----------------------------------------------"

    echo "$GPU_LINE"

    # --------------------------------------------------------
    # Vendor
    # --------------------------------------------------------

    VENDOR=$(
        lspci -n -s "$PCI_ADDR" 2>/dev/null |
            awk '{print $3}' |
            cut -d: -f1
    )

    case "$VENDOR" in
        10de)
            GPU_VENDOR="NVIDIA"
            ;;
        1002)
            GPU_VENDOR="AMD"
            ;;
        8086)
            GPU_VENDOR="Intel"
            ;;
        *)
            GPU_VENDOR="Unknown"
            ;;
    esac

    info "Vendor: $GPU_VENDOR"

    # --------------------------------------------------------
    # PCI information
    #
    # Prefer plain `lspci -vv` (no privileges). Some systems
    # restrict the capability listing to root; when that is the
    # case, retry once with `sudo -n`, which fails immediately
    # instead of prompting. Never block on a password.
    # --------------------------------------------------------

    PCI_INFO=$(lspci -vv -s "$PCI_ADDR" 2>/dev/null || true)

    if [[ -z "$PCI_INFO" ]] ||
       grep -q 'access denied' <<< "$PCI_INFO"; then
        PCI_INFO=$(sudo -n lspci -vv -s "$PCI_ADDR" 2>/dev/null || true)
    fi

    if [[ -z "$PCI_INFO" ]]; then
        warn "Unable to read verbose PCI information."
        echo
        continue
    fi

    # --------------------------------------------------------
    # Resizable BAR capability
    #
    # Prefer the PCI capability block that contains the
    # "Physical Resizable BAR" string, and fall back to any
    # capability line mentioning "Resizable BAR".
    #
    # A missing string is NOT proof that ReBAR is unsupported;
    # it only means the state could not be determined.
    # --------------------------------------------------------

    CAP_PATTERN="Physical Resizable BAR"

    if ! grep -qi "$CAP_PATTERN" <<< "$PCI_INFO"; then
        CAP_PATTERN="Resizable BAR"
    fi

    if ! grep -qi "$CAP_PATTERN" <<< "$PCI_INFO"; then
        REBAR_UNKNOWN=1
        warn "Resizable BAR capability could not be determined."
        echo
        continue
    fi

    good "Resizable BAR capability detected."

    # Capture the PCI capability block containing the
    # Resizable BAR string, stopping at the next line with
    # the same indentation (a sibling capability).
    REBAR=$(
        awk -v pat="$CAP_PATTERN" '
            $0 ~ pat {
                found=1
                match($0, /^[[:space:]]*/)
                base = RLENGTH
                print
                next
            }

            found {
                match($0, /^[[:space:]]*/)
                if (RLENGTH > base) { print; next }
                exit
            }
        ' <<< "$PCI_INFO"
    )

    echo
    echo "Resizable BAR capability:"
    echo "$REBAR"

    # --------------------------------------------------------
    # BAR 1
    # --------------------------------------------------------

    BAR1_LINE=$(
        grep -iE 'BAR 1:.*current size:' <<< "$REBAR" |
            head -1
    )

    if [[ -z "$BAR1_LINE" ]]; then
        REBAR_UNKNOWN=1
        warn "Resizable BAR capability could not be determined (no BAR 1 size reported)."
        echo
        continue
    fi

    CURRENT=$(
        sed -n \
            's/.*current size: \([^,]*\),.*/\1/p' \
            <<< "$BAR1_LINE"
    )

    SUPPORTED=$(
        sed -n \
            's/.*supported: //p' \
            <<< "$BAR1_LINE"
    )

    info "BAR 1 current size: ${CURRENT:-unknown}"
    info "BAR 1 supported sizes: ${SUPPORTED:-unknown}"

    CURRENT_MIB=$(size_to_mib "$CURRENT")

    # --------------------------------------------------------
    # Maximum supported BAR 1 size
    # --------------------------------------------------------

    MAX_SUPPORTED_MIB=""
    MAX_SUPPORTED_RAW=""

    if [[ -n "$SUPPORTED" ]]; then
        for size in $SUPPORTED; do
            [[ "$size" =~ ^[0-9]+(MB|GB)$ ]] || continue
            mib=$(size_to_mib "$size")
            [[ -n "$mib" ]] || continue
            if [[ -z "$MAX_SUPPORTED_MIB" || "$mib" -gt "$MAX_SUPPORTED_MIB" ]]; then
                MAX_SUPPORTED_MIB="$mib"
                MAX_SUPPORTED_RAW="$size"
            fi
        done
    fi

    # --------------------------------------------------------
    # ReBAR state
    #
    #   ENABLED   capability found, current >= maximum
    #   DISABLED  capability found, current < maximum
    #   UNKNOWN   not enough information
    # --------------------------------------------------------

    if [[ -n "$CURRENT_MIB" && -n "$MAX_SUPPORTED_MIB" ]]; then

        if (( CURRENT_MIB >= MAX_SUPPORTED_MIB )); then

            good "BAR 1 is configured at the maximum supported size."
            good "Resizable BAR appears to be fully enabled."

        else

            warn "BAR 1 is smaller than the maximum supported size."
            warn "Resizable BAR is supported but does not appear to be fully enabled."

            REBAR_DISABLED=1

            REASON="Linux reports BAR 1 as ${CURRENT}, while this GPU supports sizes up to ${MAX_SUPPORTED_RAW:-${MAX_SUPPORTED_MIB} MiB}."

            show_warning \
                "$GPU_LINE" \
                "$REASON"
        fi
    else
        REBAR_UNKNOWN=1
        warn "Resizable BAR capability could not be determined."
    fi

    # --------------------------------------------------------
    # Linux PCI resource allocation
    #
    # Supporting evidence only; it does not replace the
    # Resizable BAR capability parsing above.
    # --------------------------------------------------------

    SYS_PATH="/sys/bus/pci/devices/0000:${PCI_ADDR}/resource"

    if [[ -r "$SYS_PATH" ]]; then

        BAR1_RESOURCE=$(sed -n '2p' "$SYS_PATH")

        if [[ -n "$BAR1_RESOURCE" ]]; then

            START=$(awk '{print $1}' <<< "$BAR1_RESOURCE")
            END=$(awk '{print $2}' <<< "$BAR1_RESOURCE")

            if [[ "$START" != "0x0000000000000000" &&
                  "$START" =~ ^0x[0-9a-fA-F]+$ &&
                  "$END" =~ ^0x[0-9a-fA-F]+$ ]]; then

                SIZE=$((END - START + 1))
                SIZE_MIB=$((SIZE / 1024 / 1024))

                if (( SIZE_MIB >= 1024 && SIZE_MIB % 1024 == 0 )); then
                    SIZE_HUMAN="$((SIZE_MIB / 1024)) GiB"
                else
                    SIZE_HUMAN="${SIZE_MIB} MiB"
                fi

                info "Linux BAR 1 allocation: ${SIZE_MIB} MiB ($SIZE_HUMAN)"
                info "BAR 1 address range: $START - $END"
            fi
        fi
    fi

    # --------------------------------------------------------
    # NVIDIA information
    # --------------------------------------------------------

    if [[ "$GPU_VENDOR" == "NVIDIA" ]] &&
       command -v nvidia-smi >/dev/null 2>&1; then

        NVIDIA_BAR=$(
            nvidia-smi -q 2>/dev/null |
                grep -A3 "BAR1 Memory Usage" ||
                true
        )

        if [[ -n "$NVIDIA_BAR" ]]; then
            echo
            echo "NVIDIA BAR1:"
            echo "$NVIDIA_BAR"
        fi
    fi

    echo

done

# ------------------------------------------------------------
# Final summary
# ------------------------------------------------------------

echo "=============================================="
echo "                    Summary"
echo "=============================================="

if (( REBAR_DISABLED )); then
    warn "Resizable BAR is supported but does not appear to be fully enabled."
elif (( REBAR_UNKNOWN )); then
    warn "Resizable BAR capability could not be determined for one or more GPUs."
    good "No GPU was confirmed to have a disabled Resizable BAR configuration."
else
    good "No disabled Resizable BAR configuration was detected."
fi

if (( REBAR_DISABLED && UEFI == 0 )); then
    warn "The system is not booted in UEFI mode."
fi

echo
echo "This checker is read-only."
echo "No BIOS, PCI, kernel, or driver settings were changed."
echo "=============================================="
